/**
 * Stand-in data for the preview harness.
 *
 * The app is behind a Google sign-in, so a headless browser only ever sees the
 * splash screen — which makes it impossible to check a layout without a phone
 * in hand. This is the way in: a dev-only route that renders the *real*
 * components against fixtures, so what gets screenshotted is the real markup
 * and the real stylesheet rather than a mock-up of them that drifts.
 *
 * Everything here is gated on `import.meta.env.DEV` at the point of use, so
 * none of it exists in a production build.
 *
 * The fixtures are deliberately awkward rather than tidy: the longest meaning
 * in the corpus, a word with no meaning at all, a level that is 100% started
 * and 0% held. A harness populated with comfortable data proves nothing — the
 * layouts that break are the ones nobody fed a hard case.
 */

export const PREVIEW_HASH = '#/preview';

export function isPreview(): boolean {
  return import.meta.env.DEV && window.location.hash.startsWith(PREVIEW_HASH);
}

/**
 * Whether this preview wants a brand-new account rather than a lived-in one.
 *
 * Teaching the harness to serve review states fixed one blind spot and opened
 * the opposite one: the screens as somebody sees them on their first launch —
 * every bar at zero, no streak, nothing due, the calibration curve with nothing
 * to plot — stopped being renderable at all. Those states have their own copy
 * and their own layouts, and "it looks fine with data" says nothing about them.
 *
 * A suffix on the screen name rather than a separate set of fixtures, so both
 * versions of a screen are the same component with the same props and the only
 * difference is what the storage layer answers.
 */
export function isPreviewEmpty(): boolean {
  return isPreview() && window.location.hash.endsWith(EMPTY_SUFFIX);
}

/**
 * Whether this preview wants the queue cleared rather than a backlog.
 *
 * The third account state, and the one the merged practice screen was built
 * for: everything has been met, nothing is due, and there is nothing left to
 * introduce. Before the merge that was the dead end the app had no answer to,
 * so it was a state worth never rendering; now it is the state where a round is
 * made entirely of practice, and it is the only way to look at a question that
 * carries the "extra practice" mark.
 *
 * It cannot be reached from the lived-in fixture by answering, because a
 * headless browser is not going to clear a four thousand item backlog.
 */
export function isPreviewAhead(): boolean {
  return isPreview() && window.location.hash.endsWith(AHEAD_SUFFIX);
}

